"""`corpus-graph export-vault`: an Obsidian vault of the corpus.

  Sources/<Author Year - Title>.md   the converted Markdown; every quoted line gets a block id
                                     (^cg-L42) so node notes can link to the exact paragraph
  Nodes/<Type>/<name>.md             one note per node: aliases in frontmatter (so Obsidian
                                     resolves them), typed edges as [[wikilinks]], quotes
  corpus-graph.md                    index note

The vault is regenerated from scratch each time; edit canon/, not the vault.
"""

from __future__ import annotations

import re
import shutil
from collections import defaultdict
from pathlib import Path

import yaml

from .graphstore import GraphStore
from .util import Workspace, write_text

_BAD = re.compile(r'[\\/*"<>:|?#^\[\]]')


def _safe(name: str, maxlen: int = 120) -> str:
    s = _BAD.sub(lambda m: "." if m.group(0) == ":" else " ", name)
    s = re.sub(r"\s+", " ", s).strip(" .")
    return s[:maxlen].rstrip(" .") or "untitled"


def export(ws: Workspace, dest: Path | None = None) -> Path:
    store = GraphStore.load(ws)
    dest = (dest or ws.out / "vault").resolve()
    marker = dest / ".corpus-graph-vault"
    if dest.exists():
        if not marker.exists() and any(dest.iterdir()):
            raise SystemExit(f"{dest} exists and is not a corpus-graph vault; choose another folder")
        for sub in ("Sources", "Nodes"):
            shutil.rmtree(dest / sub, ignore_errors=True)
    (dest / "Sources").mkdir(parents=True, exist_ok=True)
    marker.write_text("generated by corpus-graph export-vault; safe to delete and regenerate\n")

    # file names
    src_name: dict[str, str] = {}
    used: set[str] = set()
    for d in store.g["documents"]:
        who = ", ".join(a.split()[-1] for a in (d.get("authors") or [])[:2])
        base = _safe(f"{who} {d.get('year') or ''} - {d['title']}".strip(" -"))
        name, i = base, 2
        while name.lower() in used:
            name, i = f"{base} ({i})", i + 1
        used.add(name.lower())
        src_name[d["hash"]] = name
    node_path: dict[str, str] = {}
    used_nodes: set[str] = set()
    for n in store.g["nodes"]:
        if n["type"] == "Document":
            node_path[n["id"]] = f"Sources/{src_name[n['attrs']['hash']]}"
            continue
        base = _safe(n["canonical_name"])
        name, i = base, 2
        while f"{n['type']}/{name}".lower() in used_nodes:
            name, i = f"{base} ({i})", i + 1
        used_nodes.add(f"{n['type']}/{name}".lower())
        node_path[n["id"]] = f"Nodes/{n['type']}/{name}"

    # block ids on every cited line
    cited: dict[str, set[int]] = defaultdict(set)
    for n in store.g["nodes"]:
        for p in n["provenance"]:
            if p.get("line"):
                cited[p["doc"]].add(int(p["line"]))
    for e in store.g["edges"]:
        for p in e["provenance"]:
            if p.get("line"):
                cited[p["doc"]].add(int(p["line"]))
    for d in store.g["documents"]:
        md = ws.root / d["md_path"]
        if not md.exists():
            continue
        lines = md.read_text(encoding="utf-8").split("\n")
        fm_end = 0
        if lines and lines[0].strip() == "---":
            fm_end = next((i + 1 for i in range(1, len(lines)) if lines[i].strip() == "---"), 0)
        for ln in cited.get(d["hash"], ()):
            if fm_end < ln <= len(lines) and lines[ln - 1].strip() and not lines[ln - 1].startswith(("---", "#", "<!--")):
                lines[ln - 1] = f"{lines[ln - 1]} ^cg-L{ln}"
        write_text(dest / "Sources" / f"{src_name[d['hash']]}.md", "\n".join(lines))

    def link(nid: str) -> str:
        n = store.nodes[nid]
        return f"[[{node_path[nid]}|{n['canonical_name']}]]"

    def qlink(p: dict) -> str:
        page = f", p. {p['page']}" if p.get("page") else ""
        anchor = f"#^cg-L{p['line']}" if p.get("line") else ""
        return f"> {p['quote']}\n> — [[Sources/{src_name.get(p['doc'], p['doc'])}{anchor}|{store.doc_label(p['doc']).replace('*', '')}{page}]]"

    for n in store.g["nodes"]:
        if n["type"] == "Document":
            continue
        fm = {"cg_id": n["id"], "type": n["type"], "aliases": n.get("aliases", []), "unresolved": n.get("unresolved", False),
              "community": n.get("community"), "tags": [f"cg/{n['type']}"] + (["cg/unresolved"] if n.get("unresolved") else [])}
        body = [f"# {n['canonical_name']}", ""]
        groups = defaultdict(list)
        for d, e in store.edges_of(n["id"]):
            groups[(d, e["relation"])].append(e)
        for (d, rel), es in sorted(groups.items(), key=lambda x: (x[0][1], x[0][0])):
            body += [f"## {'→' if d == 'out' else '←'} {rel}", ""]
            for e in es:
                other = e["target"] if d == "out" else e["source"]
                body.append(f"- {link(other)} ({e['confidence']}{', derived' if e.get('derived') else ''})")
                for p in store.ranked_provenance(e)[:2]:
                    body += ["", "\n".join("  " + l for l in qlink(p).splitlines()), ""]
            body.append("")
        if n["provenance"]:
            body += ["## Mentions", ""]
            for p in n["provenance"][:40]:
                body += [qlink(p), ""]
        text = "---\n" + yaml.safe_dump(fm, allow_unicode=True, sort_keys=False).strip() + "\n---\n\n" + "\n".join(body)
        write_text(dest / f"{node_path[n['id']]}.md", text)

    idx = ["# corpus-graph", "", f"{len(store.g['documents'])} documents, {len(store.g['nodes'])} nodes. Regenerate with `corpus-graph export-vault`.", "",
           "## Sources", ""]
    idx += [f"- [[Sources/{src_name[d['hash']]}]]" for d in sorted(store.g["documents"], key=lambda d: (d.get("year") or 0))]
    idx += ["", "## Communities", ""]
    for c in store.g.get("communities", [])[:30]:
        tops = ", ".join(link(t) for t in c["top_nodes"][:6] if t in store.nodes)
        idx.append(f"- C{c['id']} ({c['size']}): {tops}")
    write_text(dest / "corpus-graph.md", "\n".join(idx) + "\n")
    return dest
